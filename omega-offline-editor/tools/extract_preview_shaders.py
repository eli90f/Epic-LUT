#!/usr/bin/env python3
"""Bundle the local Filediver preview GLSL unchanged, except recursive #include expansion.
This generates renderer inputs, not a claim of exact HD2 renderer equivalence.
"""
from pathlib import Path
import hashlib,json,re
SOURCE=Path(r'research/filediver')
PROJECT=Path(__file__).resolve().parents[1]
SHADERS=SOURCE/'cmd/filediver-gui/widgets/previews/materials/shaders'
OUTPUT=PROJECT/'native/generated_preview_shaders.h'
def hash64(value):
 data=value.encode('utf-8');mask=(1<<64)-1;m=0xc6a4a7935bd1e995;h=len(data)*m&mask
 for off in range(0,len(data)//8*8,8):
  k=int.from_bytes(data[off:off+8],'little')*m&mask;k^=k>>47;k=k*m&mask;h=(h^k)*m&mask
 tail=data[len(data)//8*8:]
 if tail:h=(h^int.from_bytes(tail,'little'))*m&mask
 h^=h>>47;h=h*m&mask;return h^(h>>47)
def expand(name,stack=()):
 if name in stack:raise ValueError('cyclic GLSL include')
 path=(SHADERS/name).resolve()
 if path.parent!=SHADERS.resolve():raise ValueError('include outside shader directory')
 text=path.read_text(encoding='utf-8')
 return re.sub(r'^#include\s+"([^"]+)"\s*$',lambda m:'// Begin source include '+m[1]+'\n'+expand(m[1],stack+(name,))+'\n// End source include '+m[1],text,flags=re.M)
def raw(name,text):
 delim='OMEGA_GLSL'
 if ')'+delim+'"' in text:raise ValueError('raw string delimiter collision')
 return 'inline constexpr const char '+name+'[] = R"'+delim+'('+text+')'+delim+'";\n'
license_text=(SOURCE/'LICENSE').read_text(encoding='utf-8')
files=['object.vert','object.geom','lut.frag','lighting.frag']
manifest=[]
for name in files:
 data=(SHADERS/name).read_bytes();manifest.append(dict(name=name,sha256=hashlib.sha256(data).hexdigest(),bytes=len(data),lines=len(data.splitlines())))
frag=(SHADERS/'lut.frag').read_text()
textures=re.findall(r'^uniform\s+(sampler\w+)\s+(\w+)\s*;',frag,flags=re.M)
textures += [('sampler2D','ibl_brdf_lut')]
block=re.search(r'uniform LutSettingsBlock\s*\{([^}]+)\}',frag,re.S)[1]
fields=re.findall(r'\b(uint|bool|float|vec2|vec3|vec4)\s+(\w+)\s*;',block)
header='''// Generated by tools/extract_preview_shaders.py. Do not hand edit.
// Source: Filediver local checkout, cmd/filediver-gui/widgets/previews/materials/shaders.
// The source preview uses custom lighting and fixed weathering; this is NOT the full game renderer.
/*
'''+license_text+'\n*/\n#pragma once\n#include <cstdint>\n#include <cstddef>\nnamespace omega::source_preview {\n'
header+=raw('kObjectVertex',expand('object.vert'))+raw('kObjectGeometry',expand('object.geom'))+raw('kLutFragment',expand('lut.frag'))
header+='struct TextureSlot {const char* name;uint32_t hash;bool array;};\ninline constexpr TextureSlot kTextureSlots[] = {\n'
for typ,name in textures:header+=' {"'+name+'",0x%08xu,%s},\n'%(hash64(name)>>32,'true' if 'Array' in typ else 'false')
header+='};\nstruct MaterialField {const char* name;uint32_t hash;const char* glslType;};\ninline constexpr MaterialField kMaterialFields[] = {\n'
for typ,name in fields:header+=' {"'+name+'",0x%08xu,"%s"},\n'%(hash64(name)>>32,typ)
header+='};\n'+raw('kProvenanceJson',json.dumps(manifest,indent=2))
header+='''// Same discrete row decision as lut.frag::getMaterialLutRow, after texture sampling.
// A negative return denotes the source transparent_lut discard condition.
inline int lutRowFromIdSamples(const float* rgba, size_t layers, bool transparent) {
 int row=0;
 for(size_t layer=0;layer<layers;++layer){
  const float* sample=rgba+layer*4;
  if(transparent && layer==1 && sample[3]>0.5f)return -1;
  for(int c=0;c<4;++c)if(sample[c]>=0.496f){row=int(layer*4)+c;break;}
 }
 return row;
}
} // namespace omega::source_preview
'''
OUTPUT.write_text(header,encoding='utf-8')
print(json.dumps(dict(output=str(OUTPUT),files=manifest,textureSlots=[dict(name=n,hash=f'{hash64(n)>>32:08x}',array='Array' in t) for t,n in textures],materialFields=[dict(name=n,type=t,hash=f'{hash64(n)>>32:08x}') for t,n in fields]),indent=2))
